"""The FastAPI application (work package A02).

:func:`create_app` assembles it, and ``uvicorn app.main:app`` finds the module attribute ``app``,
which is built on first access rather than at import (see :func:`__getattr__`). That matters for
the test suite: importing this module must not read the environment or build an engine, because
every suite runs several applications against several throwaway databases in one process.

Order of assembly, which is also the order a request meets things:

1. :class:`app.core.logging.RequestContextMiddleware` -- request id, client address, forwarded
   scheme, timing, the access log line, ``X-Request-Id`` on the way out. Outermost, so it sees
   every response including the ones an exception handler writes.
2. :class:`app.core.http.SecurityHeadersMiddleware` -- the strict SPA policy on HTML, the
   stricter API policy on everything else, plus the headers from
   ``security-architecture.md`` section 6.2.
3. :class:`app.core.http.OriginGuardMiddleware` -- a state-changing request may not come from
   another origin, including ``POST /auth/login``, which has no session to bind a CSRF token to
   yet.
4. :class:`app.core.database.UnitOfWorkMiddleware` -- one database transaction per request,
   committed on a success status **before the response is forwarded**. Its docstring explains why
   this is not a dependency with a ``yield``.
5. The route's own declaration: a role through :class:`app.auth.rbac.RoleRequirement`, or an
   explicit ``public``. Authentication, CSRF and the role comparison all happen there.
6. The handler.
7. On the way out, :func:`app.core.errors.install_error_handlers` guarantees that whatever
   happened, the client is told one of the fixed strings in ``app.core.errors.MESSAGES``.

**Routers are mounted by extending the route table, not by ``include_router``.** See
:func:`_mount`: the RBAC matrix is a frozen contract and it needs a flat, inspectable list of
routes.

**No interactive documentation is served.** ``docs_url``, ``redoc_url`` and ``openapi_url`` are
all off. Swagger UI needs an inline script and a CDN, which the strict SPA CSP forbids and which
this package is not going to loosen the policy for; the document itself is generated by
``python -m app.export_openapi`` into ``services/api/openapi.json``, which is what W01 generates
its client from and what a reviewer reads. That also means the route list has no route nobody
declared a role for.
"""

from __future__ import annotations

from collections.abc import AsyncIterator
from contextlib import asynccontextmanager

from fastapi import APIRouter, FastAPI
from slowapi.errors import RateLimitExceeded

from app import __version__, static
from app.auth.cookies import insecure_cookie_warning
from app.core import rate_limit
from app.core.caveats import C14
from app.core.database import Database, UnitOfWorkMiddleware
from app.core.errors import install_error_handlers
from app.core.http import OriginGuardMiddleware, SecurityHeadersMiddleware
from app.core.logging import (
    RequestContextMiddleware,
    configure_logging,
    get_logger,
    silence_uvicorn_handlers,
)
from app.core.settings import Settings
from app.db import ConfigError
from app.routers import api_keys, auth, health, users, workspaces

__all__ = ['create_app']

log = get_logger('app.main')

#: The API's own description. C14 is quoted verbatim from ``docs/reference/caveats.md`` through
#: :mod:`app.core.caveats`, because the OpenAPI document is what a licensee's security reviewer
#: reads before they believe anything else this product says about database access.
DESCRIPTION = f"""
Metadata store, accounts, workspaces, and roles for Backend Buddy.

{C14}

Authentication is either a session cookie, obtained from `POST /auth/login` and accompanied by
the `X-CSRF-Token` header on every state-changing request, or `Authorization: Bearer` with an API
key, which is exempt from CSRF because it carries no ambient credential. Every route declares a
minimum role; `x-backend-buddy-role` on each operation states which.
"""


def create_app(settings: Settings | None = None) -> FastAPI:
    """Build an application. ``settings`` defaults to the process environment."""
    resolved = settings or Settings.from_environment()
    configure_logging(resolved)
    rate_limit.configure(resolved)

    application = FastAPI(
        title='Backend Buddy API',
        version=__version__,
        description=DESCRIPTION,
        docs_url=None,
        redoc_url=None,
        openapi_url=None,
        lifespan=_lifespan,
    )
    application.state.settings = resolved
    database = Database(resolved)
    application.state.database = database
    application.state.limiter = rate_limit.limiter

    install_error_handlers(application)
    application.add_exception_handler(RateLimitExceeded, rate_limit.rate_limit_handler)

    # Added inner first: Starlette wraps in reverse, so RequestContextMiddleware ends up outermost
    # and UnitOfWorkMiddleware sits closest to the routes.
    application.add_middleware(UnitOfWorkMiddleware, database=database)
    application.add_middleware(OriginGuardMiddleware, settings=resolved)
    application.add_middleware(SecurityHeadersMiddleware, settings=resolved)
    application.add_middleware(RequestContextMiddleware, settings=resolved)

    for router in (
        health.router,
        auth.router,
        users.router,
        workspaces.router,
        api_keys.router,
        # Last: the SPA catch-all would otherwise shadow every route mounted after it.
        static.router,
    ):
        _mount(application, router)
    return application


def _mount(application: FastAPI, router: APIRouter) -> None:
    """Add ``router``'s routes to ``application``'s own route table.

    Why not ``include_router``: from FastAPI 0.120 it stores a lazy ``_IncludedRouter`` wrapper,
    so ``app.routes`` no longer lists the routes -- they are resolved at match time from private
    classes. The RBAC matrix is a frozen contract (``test_rbac_matrix`` walks the application and
    fails on an undeclared route), and it cannot be built from a route table that does not exist
    until a request arrives.

    Extending the table is equivalent here because each router carries its own prefix, tags and
    dependencies, and ``APIRouter`` bakes all three into every route as it is declared -- which is
    what ``test_A02_router_mounting_preserves_declarations`` asserts. Nothing is passed to
    ``include_router`` anywhere in this package, so there is no per-include prefix or dependency
    that could be lost.
    """
    application.router.routes.extend(router.routes)


@asynccontextmanager
async def _lifespan(application: FastAPI) -> AsyncIterator[None]:
    """Validate what must be true before the first request, and clean up after the last.

    The master key is read at startup and its length checked, so a missing or truncated secret
    file fails the container rather than the first connection write hours later
    (``deployment-architecture.md`` section 4). The key itself is discarded immediately: A02 needs
    only to know that it is there and well formed, and only the worker ever decrypts with it.
    """
    settings: Settings = application.state.settings
    silence_uvicorn_handlers()
    try:
        settings.read_master_key()
    except ConfigError as error:
        log.error('startup.master_key_unusable', detail=str(error))
        raise
    warning = insecure_cookie_warning(settings)
    if warning:
        log.warning('startup.insecure_cookies', detail=warning)
    log.info(
        'startup.ready',
        version=__version__,
        deployment_mode=settings.deployment_mode,
        public_origin=settings.public_origin,
        cookie_secure=settings.secure_cookies,
        cookie_samesite=settings.cookie_samesite,
        session_idle_minutes=settings.session_idle_minutes,
        session_absolute_hours=settings.session_absolute_hours,
        store=application.state.database.safe_url,
    )
    try:
        yield
    finally:
        application.state.database.dispose()


_APPLICATION: FastAPI | None = None


def __getattr__(name: str) -> FastAPI:
    """Build ``app`` on first access, so ``uvicorn app.main:app`` works and imports stay inert.

    ``uvicorn`` resolves ``app.main:app`` with :func:`getattr` on this module, which is what makes
    a lazily built application indistinguishable from a module-level one for the deployment, while
    ``import app.main`` in a test still touches no environment variable and opens no engine.
    """
    if name != 'app':
        raise AttributeError(f'module {__name__!r} has no attribute {name!r}')
    global _APPLICATION
    if _APPLICATION is None:
        _APPLICATION = create_app()
    return _APPLICATION
